class Numbers:
    """Collects scalar results and writes them as LaTeX macros.

    Every number quoted in the paper text comes from one of these files, so the
    prose cannot drift from the code.
    """

    def __init__(self, name):
        self.name = name
        self.items = {}

    def add(self, key, value, fmt="{:,.2f}"):
        if not key.isalpha():
            raise ValueError(f"LaTeX macro names must be letters only: {key}")
        if isinstance(value, str):
            self.items[key] = value
        else:
            self.items[key] = fmt.format(value)

    def write(self):
        lines = [f"% Auto-generated by the analysis pipeline ({self.name}). Do not edit."]
        for k, v in self.items.items():
            lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
        (NUMBERS / f"{self.name}.tex").write_text("\n".join(lines) + "\n")


def pct(x, digits=2):
    return f"{100 * x:.{digits}f}"


def pval_fmt(p):
    if p < 0.001:
        return "<0.001"
    return f"{p:.3f}"


def stars(p):
    return "***" if p < 0.01 else "**" if p < 0.05 else "*" if p < 0.1 else ""


def wilson(k, n, z=1.959964):
    """Wilson score interval for a binomial proportion."""
    p = k / n
    den = 1 + z**2 / n
    centre = (p + z**2 / (2 * n)) / den
    half = z * np.sqrt(p * (1 - p) / n + z**2 / (4 * n**2)) / den
    return centre - half, centre + half
